#!/usr/bin/env bash
# Regenerate the paper's numbers on a GPU host, from this repository alone.
#
#   bash setup/onstart_libero_shrink.sh           # once, on a fresh Ubuntu + CUDA 12.8 host
#   bash repro/regenerate_paper.sh smoke          # ~1.7 h on a fresh A6000: every code path, checked state by state
#   bash repro/regenerate_paper.sh paper          # about 54 GPU-hours: every run behind a printed number
#   bash repro/regenerate_paper.sh frontier composed    # tiers combine
#   DRY_RUN=1 bash repro/regenerate_paper.sh paper      # print what would run
#   bash repro/regenerate_paper.sh --analyse-only [--out DIR]   # re-analyse a finished collection
#
# Tiers come from repro/regeneration_plan.txt (hours on one RTX A6000):
#   smoke      eleven arms of the paper's configurations on one initial state per task
#   frontier   Table 1, Fig. 1, Table A1 and the latencies of Sec. 3        6.6
#   share      Fig. 2, Table A2 and Sec. 4: shift, cached share, fresh noise 6.8
#   followup   s = 3, shares of 70-75%, camera jitter, interleaved timing    6.8
#   regimes    LIBERO-Long                                                  1.1
#   composed   the composed two-step cache                                  3.4
#   idle       camera jitter on 250 states, composed-cache timing on an
#              otherwise idle machine (run it alone on the machine)         3.3
#   heldout    the held-out shift s = 2 and a second noise stream (Sec. 4) 1.5
#   screen     the cache screen and its held-out closed-loop test (Sec. 4) 8.6
#   latent_delay the per-episode latent and delayed execution (Secs. 3-4) 3.6
#   states500  the 500-state check of Sec. 3, and a second noise seed      10.9
#   checklist  the process-sharing pilot and the blockwise hooks of Sec. 5  1.7
#   hosts      runs that only pair across machines in the outcome tallies   18.6
#   extra      runs the analysis cross-checks that no printed number uses    9.5
#   paper      frontier share followup regimes composed idle heldout screen latent_delay states500 checklist
#   all        every tier
#
# Output (default regen/, or --out DIR) never touches results/:
#   regen/results/     raw runs, laid out as results/ is
#   regen/smoke/       the smoke tier's runs
#   regen/summary.json the analysis snapshot, as results/budget_shift/summary.json
#   regen/tables/, regen/figures/, regen/figure_data.json
#   regen/REPORT.txt   every regenerated run compared state by state with the
#                      shipped runs of the same configuration, every printed
#                      number checked (probes/paper_numbers.py), and the tables
#                      and figure points compared with repro/expected/
#
# Success outcomes must reproduce exactly on an RTX A6000; latencies belong to
# the machine and are reported beside the paper's. Host requirements are in
# setup/HOST_REQUIREMENTS.md.

set -u
set -o pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PLAN="$ROOT/repro/regeneration_plan.txt"
OUT="$ROOT/regen"
PYA="${PYA:-python3}"          # the analysis needs numpy and matplotlib only
ANALYSE_ONLY=0
TIERS=()

log() { printf '[%s] %s\n' "$(date +%H:%M:%S)" "$*" >&2; }

while [ $# -gt 0 ]; do
  case "$1" in
    --out) OUT="$(mkdir -p "$2" && cd "$2" && pwd)"; shift 2 ;;
    --analyse-only|--analyze-only) ANALYSE_ONLY=1; shift ;;
    -h|--help) sed -n '2,40p' "$0"; exit 0 ;;
    paper) TIERS+=(frontier share followup regimes composed idle heldout screen latent_delay states500 checklist); shift ;;
    all) TIERS+=(frontier share followup regimes composed idle heldout screen latent_delay states500 checklist hosts extra); shift ;;
    smoke|frontier|share|followup|regimes|composed|idle|heldout|screen|latent_delay|states500|checklist|hosts|extra) TIERS+=("$1"); shift ;;
    *) echo "unknown tier or option: $1 (see --help)" >&2; exit 2 ;;
  esac
done
[ ${#TIERS[@]} -gt 0 ] || [ "$ANALYSE_ONLY" = 1 ] || TIERS=(smoke)
mkdir -p "$OUT"

# One initial state per task (10 episodes per arm) of configurations that cover
# the code paths of Secs. 3 and 4's closed-loop runs: both checkpoints, two, four
# and ten steps, the whole-stack and attenuated caches, a cached prefix at a third
# shift, the composed cache, fresh noise, camera jitter, CUDA graphs and
# LIBERO-Long. The screen, the per-episode latent and delayed execution are
# regenerated by their own tiers (screen, latent_delay), not by this one.
# Each is compared state by state with every shipped run of the same
# configuration (probes/compare_regen.py).
SMOKE="\
smoke_idm_stock_2step:idm:2:1.0:1:stock \
smoke_uncond_stock_10step:uncond:10:5.0:1:stock \
smoke_idm_whole_plain_tau8:idm:10:1.0:1:whole:8 \
smoke_idm_whole_agg_tau8:idm:10:1.0:1:whole:8:a \
smoke_uncond_whole_4step_tau4:uncond:4:5.0:1:whole:4 \
smoke_idm_s3_p9_tau8:idm:10:3.0:1:whole:8@prefix=9 \
smoke_tm_idm_comp4:idm:2:1.0:1:whole:4@prefix=1 \
smoke_idm_s1_whole_tau8_rn:idm:10:1.0:1:whole:8@noise \
smoke_cam0015_idm_stock2:idm:2:1.0:1:stock@perturb=cam:0.015 \
smoke_lat_uncond_stock2_cg:uncond:2:5.0:1:stock@cudagraphs \
smoke_long_uncond_stock2:uncond:2:5.0:1:stock@suite=libero_10"

failed=()
collect() {   # <tier>
  local tier="$1" t d exp seeds env hours
  if [ "$tier" = smoke ]; then
    log "tier smoke: 11 arms x 10 initial states -> $OUT/smoke"
    bash "$ROOT/repro/run_experiment.sh" budget_shift --seeds "$SMOKE" --out "$OUT/smoke" < /dev/null \
      || failed+=("smoke")
    return
  fi
  while IFS='|' read -r t d exp seeds env hours; do
    t="$(echo "$t" | xargs)"
    case "$t" in ''|\#*) continue ;; esac
    [ "$t" = "$tier" ] || continue
    d="$(echo "$d" | xargs)"; exp="$(echo "$exp" | xargs)"
    seeds="$(echo "$seeds" | xargs)"; env="$(echo "$env" | xargs)"; hours="$(echo "$hours" | xargs)"
    log "tier $tier: $exp -> results/$d (about $hours GPU-hours$([ "$env" = "-" ] || echo ", $env"))"
    local args=("$exp" --out "$OUT/results/$d")
    [ "$seeds" = "-" ] || args+=(--seeds "$seeds")
    # stdin stays with the plan file; nothing a run starts may read it
    if [ "$env" = "-" ]; then
      bash "$ROOT/repro/run_experiment.sh" "${args[@]}" < /dev/null || failed+=("$tier:$d")
    else
      env $env bash "$ROOT/repro/run_experiment.sh" "${args[@]}" < /dev/null || failed+=("$tier:$d")
    fi
  done < "$PLAN"
}

if [ "$ANALYSE_ONLY" = 0 ]; then
  if [ "${DRY_RUN:-0}" != 1 ]; then
    bash "$ROOT/repro/run_experiment.sh" preflight || { echo "host is not ready; see setup/HOST_REQUIREMENTS.md" >&2; exit 1; }
  fi
  for tier in "${TIERS[@]}"; do collect "$tier"; done
  [ "${DRY_RUN:-0}" = 1 ] && exit 0
fi

# ------------------------------------------------------------------ analysis (CPU)
STATUS="$OUT/.status"; : > "$STATUS"
{
  echo "Regeneration report, $(date -u +%Y-%m-%dT%H:%MZ)"
  echo "tiers: ${TIERS[*]:-(analysis only)}"
  nvidia-smi --query-gpu=name,driver_version --format=csv,noheader 2>/dev/null | sed 's/^/gpu: /'
  [ ${#failed[@]} -eq 0 ] || echo "FAILED collections: ${failed[*]}"
  for f in $(find "$OUT" -name FAILED_ARMS.txt 2>/dev/null); do echo "FAILED arms in ${f%/*}: $(tr '\n' ' ' < "$f")"; done
  echo
  echo "== Cache identity gates on this host (the paper: actions within 0.17%, a 0.5 MB cache)"
  "$PYA" - "$OUT" <<'PY'
import json, sys
from pathlib import Path
gates = sorted(Path(sys.argv[1]).rglob("gate*.json"))
for g in gates:
    d = json.loads(g.read_text())
    rt = d.get("runtime") or {}
    # cached steps actually served x one stack residual x bytes per element
    shape, hits = d.get("whole_cache_entry_shape"), (d.get("whole_identity_counts") or {}).get("hits")
    width = {"bf16": 2, "fp16": 2, "no": 4}.get(rt.get("mixed_precision"), 0)
    size = hits * width * eval("*".join(map(str, shape))) if shape and hits and width else None
    print(f"  {g.relative_to(sys.argv[1])}: {d.get('ckpt')} s={rt.get('effective_action_sigma_shift')} "
          f"pass={d.get('pass')} replay error {100 * d.get('whole_identity_err', float('nan')):.3f}%"
          + (f", cache {size / 2**20:.2f} MiB ({hits} steps x {shape} {rt.get('mixed_precision')})" if size else ""))
    mf = d.get("model_facts") or {}
    if mf and "error" not in mf:
        print(f"    model: video expert {mf.get('video_expert_params', 0) / 1e9:.2f}B and action expert "
              f"{mf.get('action_expert_params', 0) / 1e9:.2f}B parameters (paper: 5B + 1B), "
              f"{mf.get('action_expert_blocks')} action blocks (30), chunk of {mf.get('action_horizon')} actions (32), "
              f"replanning every {mf.get('replan_steps')} (10), K={mf.get('num_inference_steps')} by default (10)")
if not gates:
    print("  no gate ran")
PY
  echo
  dirs=()
  [ -d "$OUT/smoke" ] && dirs+=("$OUT/smoke")
  [ -d "$OUT/results" ] && dirs+=("$OUT/results")
  if [ ${#dirs[@]} -gt 0 ]; then
    echo "== Every regenerated run against the shipped runs of the same configuration"
    "$PYA" "$ROOT/probes/compare_regen.py" "${dirs[@]}" --json "$OUT/compare.json" \
      || echo "outcomes did not reproduce" >> "$STATUS"
    echo
  fi
  if [ -d "$OUT/results" ]; then
    echo "== The analysis snapshot, re-derived from the regenerated runs"
    "$PYA" "$ROOT/probes/report_budget_shift.py" --results "$OUT/results" --out "$OUT/summary.json" > "$OUT/analysis.txt" \
      && echo "wrote summary.json (full analysis output in analysis.txt)"
    echo
    echo "== Every number printed in the paper's text (probes/paper_numbers.py)"
    "$PYA" "$ROOT/probes/paper_numbers.py" --summary "$OUT/summary.json" --compare "$OUT/compare.json" --results "$OUT/results" \
      || echo "printed numbers did not reproduce" >> "$STATUS"
    echo
    echo "== Tables and figure points, against repro/expected/"
    "$PYA" "$ROOT/probes/make_tables.py" --summary "$OUT/summary.json" --outdir "$OUT"
    "$PYA" "$ROOT/probes/make_figure.py" --summary "$OUT/summary.json" --outdir "$OUT"
    for t in "$ROOT"/repro/expected/tables/*.tex; do
      n="$(basename "$t")"
      if [ ! -f "$OUT/tables/$n" ]; then echo "  $n: not regenerated (its runs are in other tiers)"
      elif cmp -s "$t" "$OUT/tables/$n"; then echo "  $n: identical to the paper"
      else echo "  $n: differs from the paper (success columns must agree; latency columns belong to the host):"
           diff "$t" "$OUT/tables/$n" | sed 's/^/      /'
      fi
    done
    "$PYA" - "$ROOT/repro/expected/figure_data.json" "$OUT/figure_data.json" <<'PY'
import json, sys
exp, got = (json.load(open(p))["points"] for p in sys.argv[1:3])
key = lambda p: (p["figure"], p.get("panel", p.get("series")), p.get("arm", p.get("cached_share_pct")))
e, g = {key(p): p for p in exp}, {key(p): p for p in got}
same = [k for k in e if k in g and e[k] == g[k]]
succ = [k for k in e if k in g and e[k].get("success_pct") == g[k].get("success_pct")]
print(f"  figure points: {len(g)} regenerated of {len(e)} in the paper; {len(same)} identical, "
      f"{len(succ)} with identical success")
for k in e:
    if k in g and e[k].get("success_pct") != g[k].get("success_pct"):
        print(f"    success differs at {k}: paper {e[k].get('success_pct')}, regenerated {g[k].get('success_pct')}")
PY
  fi
  [ ${#failed[@]} -eq 0 ] || echo "collections failed: ${failed[*]}" >> "$STATUS"
  echo
  if [ -s "$STATUS" ]; then echo "RESULT: FAILED -- $(tr '\n' ';' < "$STATUS")"
  else echo "RESULT: every regenerated outcome and printed number that must reproduce did"; fi
} 2>&1 | tee "$OUT/REPORT.txt"
log "report: $OUT/REPORT.txt"
[ ! -s "$STATUS" ]
