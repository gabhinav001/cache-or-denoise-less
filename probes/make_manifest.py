#!/usr/bin/env python3
"""One row per shipped run: what produced it, and what it does not record.

usage: make_manifest.py [> repro/MANIFEST.md]

A complete experiment manifest is what settles whether paired comparisons
differ only in the intended intervention. Per-artefact
provenance already exists; what was missing was one place to read it, including
the runs whose provenance is INCOMPLETE. Those are the rows that matter: a
manifest that silently omitted them would answer the opposite of the question.
"""
import glob, json, os, sys

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")
FIELDS = ("seed", "gpu", "commit", "ckpt_sha256_16", "mujoco", "torch", "loadavg1")


def rows():
    for p in sorted(glob.glob(os.path.join(R, "**", "*.json"), recursive=True)):
        b = os.path.basename(p)
        if b.startswith(("gate", "_")) or b == "canonical_numbers.json":
            continue
        try:
            j = json.load(open(p))
        except Exception:
            continue
        if not isinstance(j, dict) or "rows" not in j:
            continue
        m = j.get("meta") or {}
        pv = m.get("provenance") or {}
        la = pv.get("loadavg_1_5_15")
        yield {
            "run": os.path.relpath(p, R),
            "seed": m.get("seed"),
            "episodes": len(j["rows"]),
            "arms": len({r["config"] for r in j["rows"] if isinstance(r, dict) and "config" in r}),
            "suite": m.get("suite"),
            "steps": m.get("num_inference_steps"),
            "gpu": pv.get("gpu"),
            "commit": (pv.get("commit") or "")[:12] or None,
            "ckpt_sha256_16": pv.get("ckpt_sha256_16"),
            "mujoco": pv.get("mujoco"),
            "torch": pv.get("torch"),
            "loadavg1": round(la[0], 2) if la else None,
            "init_state": any("init_state" in r for r in j["rows"][:5]),
        }


def main():
    rs = list(rows())
    print("# Experiment manifest\n")
    print(f"{len(rs)} shipped runs. Generated by `probes/make_manifest.py`; do not hand-edit.\n")
    print("`seed`, `commit` and `gpu` are the three fields a paired comparison needs to")
    print("establish that two arms differ only in the intended intervention. A dash means")
    print("the run predates that field being recorded and the gap is unrecoverable --")
    print("those rows are listed, not hidden.\n")
    miss = {f: sum(1 for r in rs if not r.get(f)) for f in FIELDS}
    print("## Completeness\n")
    print("| field | recorded | missing |")
    print("|---|---:|---:|")
    for f in FIELDS:
        print(f"| `{f}` | {len(rs)-miss[f]} | {miss[f]} |")
    print(f"| `init_state` per episode | {sum(1 for r in rs if r['init_state'])} "
          f"| {sum(1 for r in rs if not r['init_state'])} |")
    print("\n## Runs\n")
    print("| run | seed | eps | arms | steps | gpu | commit | mujoco | load |")
    print("|---|---|---:|---:|---|---|---|---|---|")
    for r in rs:
        f = lambda k: r[k] if r[k] not in (None, "") else "—"
        print(f"| `{r['run']}` | {f('seed')} | {r['episodes']} | {r['arms']} | "
              f"{f('steps')} | {f('gpu')} | `{f('commit')}` | {f('mujoco')} | {f('loadavg1')} |")
    return 0


if __name__ == "__main__":
    sys.exit(main())
